def extract_fast_forward(mach, arrival):
    """Return one complete Mac declaration or an empty unsupported result.

    The actual arrival actor is part of each variant. Layouts may not be mixed;
    runtime data contains constant policy values and source extents only.
    """
    if getattr(mach, 'architecture', None) != 'x86_64':
        return {}
    try:
        origin = arrival['provenance']['actor']
        if type(origin['offset']) is not int or type(origin['bytes']) is not int:
            return {}
        if origin['bytes'] != 315 or not 0 <= origin['offset'] - mach.slice_offset <= len(mach.data) - 315:
            return {}
        variants = (LAYOUTS, MAC_ALTERNATE)
        layouts = [{key: [row[2], row[0], row[1], row[3]]
                    for key, row in rows.items()} for rows in variants]
        proof = recognize(mach, origin['offset'], layouts, reader=declaration_bytes)
        if not proof:
            return {}
        if not any(all(proof[key] == {'offset': origin['offset'] + row[0], 'bytes': row[1]}
                       for key, row in rows.items()) for rows in variants):
            return {}
        result = copy.deepcopy(VALUES)
        result['provenance'] = proof
        # The optional radar capability is tied to the same compiler layout as
        # the timing declaration. Earlier packs retain their original payload.
        index = next(i for i, rows in enumerate(variants)
                     if all(proof[key] == {'offset': origin['offset'] + row[0], 'bytes': row[1]}
                            for key, row in rows.items()))
        rows = (RADAR_LAYOUTS, RADAR_MAC_ALTERNATE)[index]
        layout = {key: [row[2], row[0], row[1], row[3]] for key, row in rows.items()}
        radar = recognize(mach, origin['offset'], [layout], reader=declaration_bytes)
        if radar and all(radar[key] == {'offset': origin['offset'] + row[0], 'bytes': row[1]}
                         for key, row in rows.items()):
            result['radar'] = copy.deepcopy(RADAR_VALUES)
            result['radar']['provenance'] = radar
        return result
    except (KeyError, TypeError, ValueError, IndexError, OverflowError):
        return {}


