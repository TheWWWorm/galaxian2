        if briefing.get('scope') != 'first_mining_briefing' or objective.get('scope') != 'first_mining_cargo_objective': return {}
        if dialogue.get('campaign_cursor') != 0 or dialogue.get('timing') != VALUES['radio_timing']: return {}
        if shared_story.get('scope') != 'full_hold_mining_story': return {}
