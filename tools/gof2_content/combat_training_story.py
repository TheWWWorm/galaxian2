def extract_combat_training_story(mach, arrival, training, destruction, briefing, objective, dialogue, shared_story):
    try:
        if training.get('scope') != 'combat_training_encounter_construction': return {}
        if destruction.get('scope') != 'combat_training_cargo_destruction': return {}
        if briefing.get('scope') != 'first_mining_briefing' or objective.get('scope') != 'first_mining_cargo_objective': return {}
        if dialogue.get('campaign_cursor') != 0 or dialogue.get('timing') != VALUES['radio_timing']: return {}
        if shared_story.get('scope') != 'full_hold_mining_story': return {}
        proof = hashed_declarations(mach, arrival, LAYOUTS)
        if not proof: return {}
        result = copy.deepcopy(VALUES)
        result['provenance'] = proof
        return result
    except (AttributeError, KeyError, TypeError, ValueError, IndexError, OverflowError):
        return {}

